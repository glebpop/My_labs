void merge(int *array, int left, int mid, int right) {  //вспомогательная функция сортировки слияния, сливает  все
    int n1 = mid - left + 1;//количество элементов левой половины +1 считаем количество элементов а это индексы
    int n2 = right - mid;//количество элементов правой половины +1 не надо так как вычитаем mid

    int *L = (int*)malloc(n1 * sizeof(int));//создание временных массивов чтобы не потерять элементы(перезапись штука страшная)
    int *R = (int*)malloc(n2 * sizeof(int));

    for (int i = 0; i < n1; i++){//закидываем элеметы ориг массива в эти, чтобы перезаписать исходный и не потерять элементы
		L[i] = array[left + i];
	}
    for (int j = 0; j < n2; j++){
		R[j] = array[mid + 1 + j];//mid это часть left так что +1
	}

    int i = 0, j = 0, k = left;//i - элемент в массиве L, j - элемент в массиве R, k - куда записываем в исходном массиве

    while (i < n1 && j < n2) {//что делаем, сравниваем элементы двух массивов
        if (L[i] <= R[j]) {//если  левый меньше либо равен правому, то он будет первым
            array[k] = L[i];//собственно ставим его
            i++;
        } else {
            array[k] = R[j];//если левый больше правого, правый идет в начало
            j++;
        }
        k++;//движение по ячейкам, как только в одном из массивов закончатся элементы, цикл завершится
    }

    while (i < n1){//перекладываем остатки из массивов в отсортированный, если в массивах и остался элемент то он наибольший
		array[k] = L[i];
		i++;
		k++;
	}
    while (j < n2){//так что можно не делать доп проверок
		array[k] = R[j];
		j++;
		k++;
	}

    free(L);//очистка мусора
    free(R);
}

void mergeSort(int *array, int left, int right) { //сортировка слиянием, разделяет массив на отдельные элементы передается массив и откуда до куда сортировать
    if (left < right) { //рекурсия, начинаем сравнивать элементы
        int mid = left + (right - left) / 2;//поиск середины
        mergeSort(array, left, mid);//сортируем левую половину
        mergeSort(array, mid + 1, right);//сортируем правую половину
        merge(array, left, mid, right);//сливаем все в одно
    }
}//логика: благодаря рекурсии она смотрит на разные части массива и запоминает что она разделила, как только остался 1 элемент она их скеливает merge
