int* darray(int size){//возвращает указатель на  целое число где находится созданный массив
        int *array;
        array = (int*)malloc(size*sizeof(int)); //объявление массива
        if(array == NULL){ //если будет запись в пустоту малок вернует нулл, это проверка чтобы прога не упала в непредвиденных случаях
                printf("Ошибка выделения памяти\n");
                return NULL;
                }
        for(int i = 0; i < size; i++){
                array[i] = rand() % 1000; //заполнение массива от 0 до 999, в мейне создается сид для функции
                }
        return array;//возвращение указателя на участок памяти где лежит неприкосновенный оригинал
}
