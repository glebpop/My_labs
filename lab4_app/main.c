// NULL - указатель на нечего, чтобы дать программе возможность не читтаь участок памяти. Макрос - фиксированная константа, заменяющаяся на значение


int main(){

    srand(time(NULL)); //матрешка: time(NULL) передает настоящее время, srand генерирует сид для rand(сохраняет сид внутри себя)
//почему null мне не нужны каждые секунды, достаточно просто вернуть значение не записывая

    int sizes[] = {10, 1000, 10000, 100000};//массив размеров, это задание
    int num_sizes = 4;//количество элементов в массиве выше

    printf("========================================================================\n");
    printf("|  ВРЕМЯ ВЫПОЛНЕНИЯ СОРТИРОВОК (в секундах)                            |\n");
    printf("========================================================================\n");
    printf("| Размер массива |   Пузырек   |   Вставки   |   Слияние   |           |\n");
    printf("========================================================================\n");


    for (int i = 0; i < num_sizes; i++) {//начало выполнения, цикл берет по размеру, создает массив согласно размеру, и проходится по всем сортировкам
        int size = sizes[i];//какой сейчас размер?


        int *original = darray(size);//создание массива по размеру
        if (original == NULL) return 1;//подробнее в arrays/darray.c


        double t_bubble = testSort(bubbleSort, original, size, 0);//подробнее в sorts_metod
        double t_insert = testSort(insertionSort, original, size, 0);
        double t_merge  = testSort(NULL, original, size, 1);


        printf("| %14d | %10.4f | %10.4f | %10.4f |              |\n", size, t_bubble, t_insert, t_merge); //вывод размеров и значений сортировок


        free(original);//очищаем от отработанного
    }
    printf("========================================================================\n");

    return 0;

}
